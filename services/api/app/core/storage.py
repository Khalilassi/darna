"""Storage adapters (selected by ``DARNA_STORAGE_BACKEND``: ``local`` or ``s3``).

Private documents
    Always encrypted by the application with Fernet (AES-128-CBC + HMAC) *before* they leave the
    process, so the bytes at rest are ciphertext on any backend. On S3 they are additionally stored
    with server-side encryption (SSE-KMS when ``DARNA_S3_KMS_KEY_ID`` is set, otherwise SSE-S3) in a
    private bucket that must block all public access.
Public listing photos
    Decoded and re-encoded with Pillow (drops EXIF/GPS metadata), then stored under a random key.
    Locally they are served from /media; on S3 they are served from ``DARNA_MEDIA_BASE_URL``
    (a CDN or the public bucket's URL).

The S3 adapter works with AWS S3 and S3-compatible stores (MinIO, Cloudflare R2, etc.) via
``DARNA_S3_ENDPOINT_URL``. Credentials come from the standard AWS credential chain (env vars,
instance/task role) — never from this codebase.
"""
from __future__ import annotations

import io
import os
import secrets
import tempfile
from pathlib import Path
from typing import Protocol

from PIL import Image, UnidentifiedImageError

from app.core.config import get_settings
from app.core.crypto import multi_fernet
from app.core.errors import ValidationFailed

ALLOWED_DOC_TYPES = {"application/pdf", "image/jpeg", "image/png", "image/webp"}
MAGIC = {
    b"%PDF": "application/pdf",
    b"\xff\xd8\xff": "image/jpeg",
    b"\x89PNG": "image/png",
    b"RIFF": "image/webp",
}


def sniff_type(data: bytes) -> str | None:
    for magic, ctype in MAGIC.items():
        if data.startswith(magic):
            return ctype
    return None


def _check_key(key: str) -> str:
    # Keys are generated by us; reject anything else to rule out path traversal / key injection.
    stem, _, ext = key.partition(".")
    if not stem.isalnum() or (ext and ext != "jpg"):
        raise ValueError("invalid storage key")
    return key


# A small compressed file can declare a huge canvas ("decompression bomb"); refuse before decoding.
MAX_IMAGE_PIXELS = 40_000_000  # ~ 8000 x 5000, well above any phone camera


def process_image(data: bytes, max_side: int = 2048) -> tuple[bytes, int, int]:
    """Validate and re-encode an uploaded photo. Returns (jpeg_bytes, width, height)."""
    try:
        img = Image.open(io.BytesIO(data))  # lazy: reads the header only
        if img.width * img.height > MAX_IMAGE_PIXELS:
            raise ValidationFailed("Image dimensions are too large", code="image_too_large")
        img.verify()
        img = Image.open(io.BytesIO(data))
    except (UnidentifiedImageError, OSError) as exc:
        raise ValidationFailed("Unsupported or corrupt image", code="invalid_image") from exc
    if img.format not in {"JPEG", "PNG", "WEBP"}:
        raise ValidationFailed("Only JPEG, PNG or WEBP images are accepted", code="invalid_image")
    img = img.convert("RGB")
    img.thumbnail((max_side, max_side))
    out = io.BytesIO()
    img.save(out, format="JPEG", quality=85, optimize=True)  # fresh encode -> no EXIF/GPS
    return out.getvalue(), img.width, img.height


class PrivateStorage(Protocol):
    def put(self, data: bytes) -> str: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def rotate(self, key: str) -> None: ...


class PublicStorage(Protocol):
    def put_image(self, data: bytes, max_side: int = 2048) -> tuple[str, int, int]: ...
    def delete(self, key: str) -> None: ...
    def url(self, key: str) -> str: ...


# --------------------------------------------------------------------------- local filesystem
class LocalEncryptedStorage:
    def __init__(self, root: Path, key: str):
        self.root = root / "private"
        self.root.mkdir(parents=True, exist_ok=True)
        self.fernet = multi_fernet(key)

    def _path(self, key: str) -> Path:
        return self.root / _check_key(key)

    def put(self, data: bytes) -> str:
        key = secrets.token_hex(24)
        self._path(key).write_bytes(self.fernet.encrypt(data))
        return key

    def get(self, key: str) -> bytes:
        return self.fernet.decrypt(self._path(key).read_bytes())

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def rotate(self, key: str) -> None:
        """Re-encrypt one object with the primary key (no-op content-wise; readable before and after)."""
        p = self._path(key)
        rotated = self.fernet.rotate(p.read_bytes())
        # Write a uniquely named sibling temp file, fsync it, then atomically swap. An interruption never
        # leaves the document truncated, concurrent rotations never share a temp file, and a failed write
        # never leaves an orphaned encrypted copy behind.
        fd, tmp = tempfile.mkstemp(dir=p.parent, prefix=f".{p.name}.", suffix=".rotating")
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(rotated)
                f.flush()
                os.fsync(f.fileno())
            os.replace(tmp, p)
        finally:
            if os.path.exists(tmp):
                os.unlink(tmp)


class PublicMediaStorage:
    def __init__(self, root: Path):
        self.root = root / "public"
        self.root.mkdir(parents=True, exist_ok=True)

    def put_image(self, data: bytes, max_side: int = 2048) -> tuple[str, int, int]:
        jpeg, w, h = process_image(data, max_side)
        key = f"{secrets.token_hex(16)}.jpg"
        (self.root / key).write_bytes(jpeg)
        return key, w, h

    def delete(self, key: str) -> None:
        (self.root / _check_key(Path(key).name)).unlink(missing_ok=True)

    def url(self, key: str) -> str:
        return f"{get_settings().public_base_url}/media/{key}"


# --------------------------------------------------------------------------- S3 / S3-compatible
def _s3_client():
    import boto3  # optional dependency, only needed for the s3 backend

    s = get_settings()
    return boto3.client("s3", region_name=s.s3_region, endpoint_url=s.s3_endpoint_url or None)


class S3EncryptedStorage:
    def __init__(self, bucket: str, key: str, prefix: str = "documents/", kms_key_id: str | None = None, client=None):
        self.bucket, self.prefix, self.kms_key_id = bucket, prefix, kms_key_id
        self.fernet = multi_fernet(key)
        self.client = client or _s3_client()

    def _obj(self, key: str) -> str:
        return f"{self.prefix}{_check_key(key)}"

    def _sse(self) -> dict:
        if self.kms_key_id:
            return {"ServerSideEncryption": "aws:kms", "SSEKMSKeyId": self.kms_key_id}
        return {"ServerSideEncryption": "AES256"}

    def put(self, data: bytes) -> str:
        key = secrets.token_hex(24)
        self.client.put_object(Bucket=self.bucket, Key=self._obj(key), Body=self.fernet.encrypt(data),
                               ContentType="application/octet-stream", **self._sse())
        return key

    def get(self, key: str) -> bytes:
        body = self.client.get_object(Bucket=self.bucket, Key=self._obj(key))["Body"].read()
        return self.fernet.decrypt(body)

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=self._obj(key))

    def rotate(self, key: str) -> None:
        body = self.client.get_object(Bucket=self.bucket, Key=self._obj(key))["Body"].read()
        self.client.put_object(Bucket=self.bucket, Key=self._obj(key), Body=self.fernet.rotate(body),
                               ContentType="application/octet-stream", **self._sse())


class S3PublicMediaStorage:
    def __init__(self, bucket: str, base_url: str, prefix: str = "media/", client=None):
        self.bucket, self.prefix, self.base_url = bucket, prefix, base_url.rstrip("/")
        self.client = client or _s3_client()

    def put_image(self, data: bytes, max_side: int = 2048) -> tuple[str, int, int]:
        jpeg, w, h = process_image(data, max_side)
        key = f"{secrets.token_hex(16)}.jpg"
        self.client.put_object(Bucket=self.bucket, Key=f"{self.prefix}{key}", Body=jpeg, ContentType="image/jpeg",
                               CacheControl="public, max-age=31536000, immutable")
        return key, w, h

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=f"{self.prefix}{_check_key(Path(key).name)}")

    def url(self, key: str) -> str:
        return f"{self.base_url}/{self.prefix}{key}"


# --------------------------------------------------------------------------- factories
_private: PrivateStorage | None = None
_public: PublicStorage | None = None


def private_storage() -> PrivateStorage:
    global _private
    if _private is None:
        s = get_settings()
        if s.storage_backend == "s3":
            _private = S3EncryptedStorage(s.s3_private_bucket, s.document_encryption_key, kms_key_id=s.s3_kms_key_id)
        else:
            _private = LocalEncryptedStorage(s.storage_dir, s.document_encryption_key)
    return _private


def public_storage() -> PublicStorage:
    global _public
    if _public is None:
        s = get_settings()
        if s.storage_backend == "s3":
            _public = S3PublicMediaStorage(s.s3_public_bucket, s.media_base_url)
        else:
            _public = PublicMediaStorage(s.storage_dir)
    return _public


def reset_storage() -> None:
    global _private, _public
    _private = _public = None
